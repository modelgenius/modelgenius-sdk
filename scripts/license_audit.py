#!/usr/bin/env python
"""License audit for the modelgenius-sdk runtime dependency closure.

Walks the installed dependency closure rooted at ``modelgenius-sdk`` (dev
tooling and environment noise are never audited), resolves each
distribution's license from its metadata, and enforces a permissive
allowlist — the gate that keeps copyleft out of the customer install.

The committed inventory at ``docs/license_inventory.md`` is the
customer/legal-facing artifact. It deliberately records (package, license)
pairs WITHOUT versions so routine upstream releases don't churn the file;
the audited set changes only when a dependency is added/removed or changes
license — exactly the events that should fail CI and force a human look.

Usage:
    python scripts/license_audit.py            # print inventory + verdict
    python scripts/license_audit.py --check    # CI gate: allowlist + committed file current
    python scripts/license_audit.py --write    # regenerate docs/license_inventory.md
"""

from __future__ import annotations

import argparse
import re
import sys
from importlib.metadata import PackageNotFoundError, distribution
from pathlib import Path

ROOT_PACKAGE = "modelgenius-sdk"
INVENTORY_PATH = Path(__file__).resolve().parent.parent / "docs" / "license_inventory.md"

# SPDX-ish identifiers acceptable in the customer install closure. Anything
# outside this set — including UNKNOWN — fails the audit. Copyleft is a
# deliberate omission, not an oversight.
ALLOWED_LICENSES = {
    "Apache-2.0",
    "BSD-2-Clause",
    "BSD-3-Clause",
    "ISC",
    "MIT",
    "PSF-2.0",
}

# Trove classifier names -> canonical identifiers, for distributions that
# predate PEP 639 License-Expression metadata.
CLASSIFIER_MAP = {
    "Apache Software License": "Apache-2.0",
    "BSD License": "BSD-3-Clause",
    "ISC License (ISCL)": "ISC",
    "MIT License": "MIT",
    "Python Software Foundation License": "PSF-2.0",
}

_HEADER = """\
# License Inventory — runtime dependency closure

The complete set of software installed by `pip install modelgenius-sdk`,
with each component's license. Generated by `scripts/license_audit.py
--write` and enforced in CI (`license-audit` job): the build fails if this
file is stale or if any license leaves the permissive allowlist (no
copyleft). Versions are deliberately omitted so routine upstream releases
don't churn this file — the audited set is (package, license).

| Package | License |
| --- | --- |
"""


def _canon(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def resolve_license(metadata) -> str:
    """Best-effort canonical license id from distribution metadata."""
    expression = (metadata.get("License-Expression") or "").strip()
    if expression:
        return expression
    license_field = (metadata.get("License") or "").strip()
    if license_field and "\n" not in license_field and len(license_field) <= 40:
        return license_field
    for classifier in metadata.get_all("Classifier") or []:
        if classifier.startswith("License ::"):
            name = classifier.split("::")[-1].strip()
            return CLASSIFIER_MAP.get(name, name)
    return "UNKNOWN"


def license_allowed(license_id: str) -> bool:
    """Exact allowlist match; compound SPDX expressions need every part allowed."""
    if license_id in ALLOWED_LICENSES:
        return True
    parts = re.split(r"\s+(?:AND|OR)\s+", license_id)
    return len(parts) > 1 and all(part.strip("() ") in ALLOWED_LICENSES for part in parts)


def dependency_closure(root: str) -> list:
    """Installed distributions reachable from `root` via runtime requires."""
    seen: set = set()
    stack = [root]
    found = []
    while stack:
        name = _canon(stack.pop())
        if name in seen:
            continue
        seen.add(name)
        try:
            dist = distribution(name)
        except PackageNotFoundError:
            continue  # dependency behind a false environment marker
        found.append(dist)
        for requirement in dist.requires or []:
            body, _, marker = requirement.partition(";")
            if "extra ==" in marker:
                continue  # optional extra, not part of the runtime closure
            match = re.match(r"\s*([A-Za-z0-9._-]+)", body)
            if match:
                stack.append(match.group(1))
    return sorted(found, key=lambda d: d.metadata["Name"].lower())


def render_inventory(rows: list) -> str:
    return _HEADER + "".join(f"| {name} | {license_id} |\n" for name, license_id in rows)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument(
        "--check", action="store_true",
        help="fail unless allowlist passes and the committed inventory is current",
    )
    mode.add_argument("--write", action="store_true", help="regenerate docs/license_inventory.md")
    args = parser.parse_args()

    dists = dependency_closure(ROOT_PACKAGE)
    if not any(_canon(d.metadata["Name"]) == ROOT_PACKAGE for d in dists):
        print(f"ERROR: {ROOT_PACKAGE} is not installed; run `pip install .` first.")
        return 2

    rows = [(d.metadata["Name"], resolve_license(d.metadata)) for d in dists]
    violations = [(name, lic) for name, lic in rows if not license_allowed(lic)]

    for dist, (name, lic) in zip(dists, rows):
        marker = "" if license_allowed(lic) else "  <-- NOT ALLOWED"
        print(f"{name} {dist.version}: {lic}{marker}")

    if violations:
        print(f"\nFAIL: {len(violations)} distribution(s) outside the permissive allowlist.")
        return 1

    if args.write:
        INVENTORY_PATH.write_text(render_inventory(rows))
        print(f"\nWrote {INVENTORY_PATH}")
        return 0

    if args.check:
        expected = render_inventory(rows)
        actual = INVENTORY_PATH.read_text() if INVENTORY_PATH.exists() else ""
        if actual != expected:
            print(
                "\nFAIL: docs/license_inventory.md is stale — regenerate with "
                "`python scripts/license_audit.py --write`."
            )
            return 1

    print("\nOK: all licenses permissive" + (", inventory current" if args.check else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
